"""Generate pseudo-labels for unlabelled images, using a larger model as teacher.

    python data/adapters/pseudo_label.py --n 2500

WHAT THIS IS AND IS NOT. These labels are a model's opinion, not ground truth.
They exist because the BDD100K images were supplied without their label file, and
they make one specific thing possible: **distillation** -- training a small fast
student to reproduce a large slow teacher's behaviour on this domain.

The ceiling is the teacher. A student trained this way cannot detect anything the
teacher misses, and it will faithfully learn the teacher's mistakes, including the
false positives on the ego vehicle's own hood. Any mAP measured against these
labels reports agreement with the teacher, NOT correctness. Real ground truth
(``det_train.json``) is still required for a real evaluation, and this file never
pretends otherwise -- the dataset.yaml it writes records the provenance so a later
reader cannot mistake these for annotations.

What it is genuinely good for:
  * a smaller, faster model specialised to dashcam scenes rather than to COCO
  * an end-to-end exercise of the training pipeline before the labels arrive
  * a measurable teacher/student speed-accuracy trade-off

Confidence threshold matters more here than at inference time. A low threshold
floods the student with false positives it will learn as real; a high one teaches
it that hard objects are background. The default is deliberately stricter than the
inference default.
"""

from __future__ import annotations

import argparse
import random
import sys
from collections import Counter
from datetime import date
from pathlib import Path

import cv2
import numpy as np

PROJECT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(PROJECT))

from core.config import load_config
from core.types import class_name
from data.adapters.bdd100k import BASE_CLASSES, Record, write_split
from models.perception.factory import build_detector


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--images", type=Path, default=PROJECT / "data/raw/images")
    ap.add_argument("--out", type=Path, default=PROJECT / "data/processed/bdd100k_pseudo")
    ap.add_argument("--n", type=int, default=2500, help="images to label")
    ap.add_argument("--val-fraction", type=float, default=0.2)
    ap.add_argument("--teacher", default="yolov8m.pt")
    ap.add_argument("--conf", type=float, default=0.4,
                    help="stricter than inference: a low bar teaches false positives")
    ap.add_argument("--min-box-px", type=float, default=12.0)
    ap.add_argument("--seed", type=int, default=5)
    ap.add_argument("--batch", type=int, default=16)
    args = ap.parse_args(argv)

    paths = sorted(args.images.glob("*.jpg"))
    if not paths:
        raise SystemExit(f"no images under {args.images}")
    rng = random.Random(args.seed)
    sample = rng.sample(paths, min(args.n, len(paths)))
    print(f"{len(paths):,} available; labelling {len(sample):,} with {args.teacher} "
          f"at conf >= {args.conf}")

    cfg = load_config(PROJECT / "configs/default.yaml").detector
    cfg = cfg.model_copy(update={
        "kind": "yolov8", "conf_threshold": args.conf,
        "yolov8": cfg.yolov8.model_copy(
            update={"weights": PROJECT / "models/perception/weights" / args.teacher}),
    })
    det = build_detector(cfg)

    records: list[Record] = []
    totals: Counter = Counter()
    for i in range(0, len(sample), args.batch):
        chunk = sample[i:i + args.batch]
        imgs, keep = [], []
        for p in chunk:
            im = cv2.imread(str(p))
            if im is not None:
                imgs.append(im); keep.append(p)
        if not imgs:
            continue
        for p, im, r in zip(keep, imgs, det.infer_batch(imgs)):
            rec = Record(name=p.name, timeofday="unknown", weather="unknown")
            for b, cid in zip(r.boxes_px, r.class_ids):
                x0, y0, x1, y1 = (float(v) for v in b)
                if (y1 - y0) < args.min_box_px:
                    continue
                name = class_name(int(cid))
                rec.boxes.append((name, x0, y0, x1, y1))
                totals[name] += 1
            records.append(rec)
        if (i // args.batch) % 20 == 0:
            print(f"  {len(records):5d}/{len(sample)} labelled", flush=True)
    det.close()

    rng.shuffle(records)
    n_val = max(1, int(round(len(records) * args.val_fraction)))
    val, train = records[:n_val], records[n_val:]

    args.out.mkdir(parents=True, exist_ok=True)
    c_train = write_split(train, args.images, args.out, "train", BASE_CLASSES, link=True)
    c_val = write_split(val, args.images, args.out, "val", BASE_CLASSES, link=True)

    yaml_lines = [
        "# PSEUDO-LABELS. Generated by data/adapters/pseudo_label.py.",
        "# These are a model's predictions, NOT ground-truth annotations.",
        "# Any metric measured against them reports AGREEMENT WITH THE TEACHER,",
        "# not correctness. Real evaluation needs BDD100K's det_train.json.",
        "name: bdd100k-pseudo",
        "task: detection",
        "label_source: pseudo",
        f"teacher: {args.teacher}",
        f"teacher_conf: {args.conf}",
        f"created: {date.today().isoformat()}",
        "",
        f"path: {args.out.resolve().as_posix()}",
        "train: images/train",
        "val: images/val",
        "",
        "names:",
        *[f"  {i}: {c}" for i, c in enumerate(BASE_CLASSES)],
    ]
    (args.out / "dataset.yaml").write_text("\n".join(yaml_lines) + "\n", encoding="utf-8")

    total = c_train + c_val
    empty = sum(1 for r in records if not r.boxes)
    print("=" * 62)
    print(f"labelled {len(records):,} images -> {len(train):,} train / {len(val):,} val")
    print(f"  boxes      " + ", ".join(f"{k}={v:,}" for k, v in total.most_common()))
    print(f"  per image  {sum(total.values())/max(1,len(records)):.2f}")
    print(f"  empty      {empty} ({100*empty/max(1,len(records)):.1f}%)")
    print(f"  dataset    {args.out / 'dataset.yaml'}")
    print("=" * 62)
    print("REMINDER: these are pseudo-labels. mAP against them measures agreement")
    print("with the teacher, not correctness.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
