def _load_reference_frame(cfg: Config, source: str, frame_index: int) -> np.ndarray:
    """Grab one frame from a video or image folder for calibration/verification."""
    from src.io import open_source  # local import: io imports config, not calibrate

    io_cfg = cfg.io.model_copy(update={"start_frame": frame_index, "max_frames": 1})
    with open_source(source, io_cfg) as src:
        for frame in src:
            return frame.image
    raise ValueError(f"source {source} has no frame at index {frame_index}")


def _cmd_homography(args: argparse.Namespace, cfg: Config) -> int:
    image = _load_reference_frame(cfg, args.source, args.frame)
    if cfg.calibration.undistort:
        intr = Intrinsics.load(cfg.calibration.intrinsics_path)
        image = intr.undistort(image)

    if args.points:
        vals = [float(v) for v in args.points.replace(";", ",").split(",")]
        if len(vals) % 2 != 0 or len(vals) < 8:
            raise ValueError(
                f"--points needs an even count of at least 8 numbers "
                f"(4 xy pairs), got {len(vals)}"
            )
        image_points = np.array(vals, dtype=np.float64).reshape(-1, 2)
    else:
        image_points = pick_points_interactively(image, n=4)

    if args.world_points:
        wvals = [float(v) for v in args.world_points.replace(";", ",").split(",")]
        world_points = np.array(wvals, dtype=np.float64).reshape(-1, 2)
    else:
        world_points = rectangle_world_points(args.lane_width, args.near, args.far)
    if len(world_points) != len(image_points):
        raise ValueError(
            f"{len(image_points)} image points but {len(world_points)} world points"
        )

    H, residual = solve_ground_homography(image_points, world_points)
    h, w = image.shape[:2]
    camera = CameraModel(
        H_image_to_ground=H,
        image_size=(w, h),
        undistort_applied=cfg.calibration.undistort,
        residual_m=residual,
        source_points_px=image_points,
        source_points_m=world_points,
    )
    out = camera.save(args.out or cfg.calibration.homography_path)
    print(f"\nhomography -> {out}")
    print(f"  image size       : {w}x{h}")
    print(f"  undistorted first: {camera.undistort_applied}")
    print(f"  correspondences  : {len(image_points)}")
    print(f"  max fit residual : {residual:.6f} m")
    if len(image_points) == 4:
        print(
            "  note: with exactly 4 points the fit is exact, so this residual is ~0\n"
            "        by construction and is NOT evidence of accuracy. Run `verify`."
        )
    print(f"  horizon row      : v = {float(camera.horizon_v(w / 2)[0]):.1f} px at image centre")
    return 0


def _cmd_verify(args: argparse.Namespace, cfg: Config) -> int:
    camera = CameraModel.load(cfg.calibration.homography_path)
    image = _load_reference_frame(cfg, args.source, args.frame)
    if cfg.calibration.undistort:
        image = Intrinsics.load(cfg.calibration.intrinsics_path).undistort(image)
    h, w = image.shape[:2]
    camera = camera.for_image_size((w, h))

    bev = camera.warp_to_bev(image, cfg.bev)
    gridded = draw_bev_grid(bev, cfg.bev)
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    bev_path = out_dir / "bev_grid.png"
    cv2.imwrite(str(bev_path), gridded)

    # Draw the calibration quad and the horizon back onto the original frame.
    annotated = image.copy()
    horizon = float(camera.horizon_v(w / 2)[0])
    if np.isfinite(horizon):
        cv2.line(annotated, (0, int(horizon)), (w, int(horizon)), (0, 0, 255), 2)
        cv2.putText(
            annotated, "horizon", (12, int(horizon) - 10),
            cv2.FONT_HERSHEY_SIMPLEX, 0.7, (0, 0, 255), 2,
        )
    for y_m in np.arange(
        cfg.bev.y_min_m, cfg.bev.y_max_m + 1e-6, cfg.bev.grid_step_m, dtype=np.float64
    ):
        span = np.array([[cfg.bev.x_min_m, y_m], [cfg.bev.x_max_m, y_m]])
        px = camera.ground_to_image(span)
        cv2.line(
            annotated,
            tuple(np.int32(px[0])), tuple(np.int32(px[1])),
            (0, 255, 0), 2,
        )
        cv2.putText(
            annotated, f"{y_m:.0f} m", (int(px[1][0]) - 70, int(px[1][1]) - 6),
            cv2.FONT_HERSHEY_SIMPLEX, 0.55, (0, 255, 0), 2,
        )
    if camera.source_points_px is not None:
        for px, pm in zip(camera.source_points_px, camera.source_points_m):
            cv2.circle(annotated, (int(px[0]), int(px[1])), 7, (255, 0, 255), -1)
            cv2.putText(
                annotated, f"({pm[0]:+.2f}, {pm[1]:.1f})m",
                (int(px[0]) + 10, int(px[1]) + 6),
                cv2.FONT_HERSHEY_SIMPLEX, 0.5, (255, 0, 255), 2,
            )
    ann_path = out_dir / "calibration_check.png"
    cv2.imwrite(str(ann_path), annotated)

    print(f"\nverification images ->\n  {bev_path}\n  {ann_path}")
    print(f"  horizon row: v = {horizon:.1f} px  (image height {h})")

    if args.width_columns:
        u_left, u_right = (float(v) for v in args.width_columns.split(","))
        rows = list(np.linspace(horizon + 0.15 * (h - horizon), h - 1, 8))
        table = measure_width_between_verticals(camera, u_left, u_right, rows)
        print(
            f"\n  ground separation between image columns u={u_left:.0f} and "
            f"u={u_right:.0f}:"
        )
        for dist_m, sep_m in table:
            print(f"    at {dist_m:6.1f} m ahead -> {sep_m:6.2f} m apart")
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="calibrate", description="Camera intrinsics and ground-plane homography."
    )
    parser.add_argument("--config", default="configs/default.yaml", help="YAML config path")
    sub = parser.add_subparsers(dest="command", required=True)

    p_int = sub.add_parser("intrinsics", help="calibrate from a chessboard image folder")
    p_int.add_argument("--images", required=True, help="folder of chessboard images")
    p_int.add_argument("--out", default=None, help="output YAML (default: from config)")
    p_int.add_argument("--debug-dir", default=None, help="write corner visualisations here")
    p_int.set_defaults(func=_cmd_intrinsics)

    p_hom = sub.add_parser("homography", help="solve the image-to-ground homography")
    p_hom.add_argument("--source", required=True, help="video file or image folder")
    p_hom.add_argument("--frame", type=int, default=0, help="frame index to calibrate on")
    p_hom.add_argument(
        "--points",
        default=None,
        help="image points 'u1,v1,u2,v2,...' in order near-left, near-right, "
        "far-left, far-right. Omit to click them interactively.",
    )
    p_hom.add_argument(
        "--world-points", default=None, help="explicit world points 'x1,y1,x2,y2,...' in metres"
    )
    p_hom.add_argument("--lane-width", type=float, default=3.5, help="rectangle width, metres")
    p_hom.add_argument("--near", type=float, default=5.0, help="near edge distance, metres")
    p_hom.add_argument("--far", type=float, default=30.0, help="far edge distance, metres")
    p_hom.add_argument("--out", default=None, help="output YAML (default: from config)")
    p_hom.set_defaults(func=_cmd_homography)

    p_ver = sub.add_parser("verify", help="warp to bird's-eye and overlay a metre grid")
    p_ver.add_argument("--source", required=True, help="video file or image folder")
    p_ver.add_argument("--frame", type=int, default=0, help="frame index to verify on")
    p_ver.add_argument("--out-dir", default="outputs/calibration", help="where to write PNGs")
    p_ver.add_argument(
        "--width-columns",
        default=None,
        help="'u_left,u_right': report the ground separation between these two "
        "image columns at several distances. Constant width = good calibration.",
    )
    p_ver.set_defaults(func=_cmd_verify)
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    cfg = load_config(args.config)
    return int(args.func(args, cfg))


if __name__ == "__main__":
    raise SystemExit(main())
