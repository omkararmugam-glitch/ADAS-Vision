def draw_bev_grid(bev_image: np.ndarray, bev: BEVConfig) -> np.ndarray:
    """Overlay a labelled metre grid on a bird's-eye image.

    Longitudinal lines are drawn every ``grid_step_m`` and labelled in metres
    forward; lateral lines every metre, with the ego centreline picked out. If
    the homography is right, real lane markings run parallel to the grid and
    keep a constant width all the way up the image.
    """
    vis = bev_image.copy()
    if vis.ndim == 2:
        vis = cv2.cvtColor(vis, cv2.COLOR_GRAY2BGR)
    w, h = bev.size_px
    ppm = bev.px_per_m

    x = float(np.ceil(bev.x_min_m))
    while x <= bev.x_max_m:
        u = int(round((x - bev.x_min_m) * ppm))
        centre = abs(x) < 1e-6
        cv2.line(vis, (u, 0), (u, h), (0, 200, 255) if centre else (70, 70, 70), 2 if centre else 1)
        if centre:
            cv2.putText(vis, "0", (u + 4, h - 8), cv2.FONT_HERSHEY_SIMPLEX, 0.4, (0, 200, 255), 1)
        x += 1.0

    y = float(np.ceil(bev.y_min_m / bev.grid_step_m) * bev.grid_step_m)
    while y <= bev.y_max_m:
        v = int(round((bev.y_max_m - y) * ppm))
        cv2.line(vis, (0, v), (w, v), (0, 255, 0), 1)
        cv2.putText(
            vis, f"{y:.0f} m", (6, v - 5), cv2.FONT_HERSHEY_SIMPLEX, 0.45, (0, 255, 0), 1
        )
        y += bev.grid_step_m
    return vis


def measure_width_between_verticals(
    camera: CameraModel, u_left: float, u_right: float, v_rows: list[float]
) -> list[tuple[float, float]]:
    """Ground separation between two image columns, sampled at several image rows.

    This is the honest check on a 4-point homography. The lane width you assumed
    is true by construction at the two rows you clicked; what it does *not*
    guarantee is that the width stays constant in between and beyond. If the
    calibration is wrong, this fans out with distance.

    Returns:
        ``(forward_distance_m, separation_m)`` per sampled row.
    """
    out: list[tuple[float, float]] = []
    for v in v_rows:
        pts = np.array([[u_left, v], [u_right, v]], dtype=np.float64)
        if not np.all(camera.is_on_ground(pts)):
            continue
        ground = camera.image_to_ground(pts)
        out.append((float(ground[:, 1].mean()), float(abs(ground[1, 0] - ground[0, 0]))))
    return out


