# Ground-plane homography
# --------------------------------------------------------------------------- #


def solve_ground_homography(
    image_points_px: np.ndarray, world_points_m: np.ndarray
) -> tuple[np.ndarray, float]:
    """Solve the image-to-ground homography from >= 4 coplanar correspondences.

    Args:
        image_points_px: ``(N, 2)`` points in image pixels, on the road surface.
        world_points_m: ``(N, 2)`` matching points in ego metres (X right, Y forward).

    Returns:
        ``(H, max_residual_m)`` where ``H`` maps homogeneous image px to ego
        metres, and the residual is the largest round-trip error over the input
        correspondences.

    Raises:
        ValueError: on mismatched shapes, fewer than 4 points, or a degenerate
            configuration (three or more points collinear).

    Note:
        With exactly 4 points the fit is exact and the residual is ~0 by
        construction, so it proves nothing about accuracy. Supply more than 4
        points for a residual that means something, and use ``verify`` either way.
    """
    img = np.asarray(image_points_px, dtype=np.float64)
    world = np.asarray(world_points_m, dtype=np.float64)
    if img.shape != world.shape or img.ndim != 2 or img.shape[1] != 2:
        raise ValueError(
            f"need matching (N, 2) arrays, got image {img.shape} and world {world.shape}"
        )
    if len(img) < 4:
        raise ValueError(f"a homography needs at least 4 points, got {len(img)}")

    H, _mask = cv2.findHomography(img, world, method=0)
    if H is None:
        raise ValueError(
            "homography solve failed: the points are degenerate. Four road points "
            "must form a proper quadrilateral, with no three collinear."
        )
    H = np.asarray(H, dtype=np.float64)
    if abs(float(np.linalg.det(H))) < 1e-12:
        raise ValueError("homography is singular; check the point correspondences")

    projected = _apply_homography(H, img)
    residual = float(np.max(np.linalg.norm(projected - world, axis=1)))
    return H, residual


def _apply_homography(H: np.ndarray, points: np.ndarray) -> np.ndarray:
    """Apply a 3x3 homography to ``(N, 2)`` points, raising at the horizon.

    Raises:
        ValueError: if any point's projective denominator is ~0, i.e. it lies on
            the vanishing line and has no finite image on the other side.
    """
    pts = np.asarray(points, dtype=np.float64).reshape(-1, 2)
    homogeneous = np.hstack([pts, np.ones((len(pts), 1))])
    out = homogeneous @ H.T
    w = out[:, 2]
    bad = np.abs(w) < _HORIZON_EPS
    if np.any(bad):
        raise ValueError(
            f"{int(bad.sum())} of {len(pts)} points lie on the horizon line, where "
            f"the ground plane maps to infinity. Filter with "
            f"CameraModel.is_on_ground() before projecting."
        )
    return out[:, :2] / w[:, None]


@dataclass(frozen=True)
class CameraModel:
    """Maps between image pixels and the ego-vehicle ground plane.

    The model is bound to one image size. Reading frames at a different
    resolution requires :meth:`for_image_size`, which rescales the homography
    rather than silently reinterpreting pixels.

    Attributes:
        H_image_to_ground: ``(3, 3)`` mapping homogeneous image px to ego metres.
        image_size: ``(width, height)`` the homography is defined for.
        undistort_applied: Whether frames were undistorted before the points were
            picked. When False the homography absorbs lens distortion.
        residual_m: Largest fit residual over the calibration correspondences.
        source_points_px: The correspondences used, kept for provenance.
        source_points_m: The matching world points, kept for provenance.
    """

    H_image_to_ground: np.ndarray
    image_size: tuple[int, int]
    undistort_applied: bool = False
    residual_m: float = 0.0
    source_points_px: np.ndarray | None = None
    source_points_m: np.ndarray | None = None

    def __post_init__(self) -> None:
        H = np.asarray(self.H_image_to_ground, dtype=np.float64)
        if H.shape != (3, 3):
            raise ValueError(f"H must be (3, 3), got {H.shape}")
        if abs(float(np.linalg.det(H))) < 1e-12:
            raise ValueError("H is singular and cannot be inverted for ground_to_image")
        object.__setattr__(self, "H_image_to_ground", H)

    @property
    def H_ground_to_image(self) -> np.ndarray:
        """``(3, 3)`` inverse mapping, ego metres to image px."""
        return np.linalg.inv(self.H_image_to_ground)

    def image_to_ground(self, points_px: np.ndarray) -> np.ndarray:
        """Project image points onto the road plane.

        Args:
            points_px: ``(N, 2)`` or ``(2,)`` image pixel coordinates. Points are
                assumed to lie on the road surface -- for a detection box, that
                means the bottom edge, not the centre.

        Returns:
            ``(N, 2)`` ego-frame metres, X right and Y forward.

        Raises:
            ValueError: if any point is on or above the horizon.
        """
        return _apply_homography(self.H_image_to_ground, points_px)

    def ground_to_image(self, points_m: np.ndarray) -> np.ndarray:
        """Project ground-plane points back into the image.

        Args:
            points_m: ``(N, 2)`` or ``(2,)`` ego-frame metres.

        Returns:
            ``(N, 2)`` image pixel coordinates, which may fall outside the frame.
        """
        return _apply_homography(self.H_ground_to_image, points_m)

    def is_on_ground(self, points_px: np.ndarray) -> np.ndarray:
        """Boolean ``(N,)`` mask: which image points project to finite road points.

        Use this to filter before :meth:`image_to_ground`, which raises rather
        than inventing a distance for a point above the horizon.
        """
        pts = np.asarray(points_px, dtype=np.float64).reshape(-1, 2)
        homogeneous = np.hstack([pts, np.ones((len(pts), 1))])
        w = homogeneous @ self.H_image_to_ground[2]
        forward = homogeneous @ self.H_image_to_ground[1]
        # Finite, and ahead of the camera: Y = forward / w must be positive.
        return (np.abs(w) >= _HORIZON_EPS) & (forward / np.where(w == 0, 1, w) > 0)

    def horizon_v(self, u: float | np.ndarray) -> np.ndarray:
        """Image row of the vanishing line at column(s) ``u``.

        Everything strictly below this row images the road plane; everything
        above it is sky, or geometry the plane assumption cannot describe.
        """
        h20, h21, h22 = self.H_image_to_ground[2]
        u_arr = np.atleast_1d(np.asarray(u, dtype=np.float64))
        if abs(h21) < _HORIZON_EPS:
            return np.full_like(u_arr, np.nan)
        return -(h20 * u_arr + h22) / h21

    def for_image_size(self, size: tuple[int, int]) -> CameraModel:
        """Return an equivalent model for frames of a different resolution.

        Rescaling a frame rescales its pixel coordinates, so the homography must
        absorb the inverse scaling to keep producing the same metres. This is the
        only sanctioned way to use one calibration across resolutions.
        """
        if tuple(size) == tuple(self.image_size):
            return self
        sx = size[0] / self.image_size[0]
        sy = size[1] / self.image_size[1]
        s_inv = np.diag([1.0 / sx, 1.0 / sy, 1.0])
        return CameraModel(
            H_image_to_ground=self.H_image_to_ground @ s_inv,
            image_size=(int(size[0]), int(size[1])),
            undistort_applied=self.undistort_applied,
            residual_m=self.residual_m,
        )

    def bev_warp_matrix(self, bev: BEVConfig) -> np.ndarray:
        """``(3, 3)`` warp from image px straight to bird's-eye px.

        BEV pixel ``(0, 0)`` is the far-left, far-forward corner of the window,
        so that forward distance increases upward on screen, as a driver sees it.
        """
        # ego metres -> BEV px: x -> (x - x_min) * ppm, y -> (y_max - y) * ppm
        ppm = bev.px_per_m
        A = np.array(
            [
                [ppm, 0.0, -bev.x_min_m * ppm],
                [0.0, -ppm, bev.y_max_m * ppm],
                [0.0, 0.0, 1.0],
            ],
            dtype=np.float64,
        )
        return A @ self.H_image_to_ground

    def warp_to_bev(self, image: np.ndarray, bev: BEVConfig) -> np.ndarray:
        """Warp a frame to the bird's-eye window defined by ``bev``."""
        h, w = image.shape[:2]
        if (w, h) != self.image_size:
            raise ValueError(
                f"frame is {(w, h)} but this CameraModel is calibrated for "
                f"{self.image_size}; call for_image_size() first"
            )
        return cv2.warpPerspective(
            image, self.bev_warp_matrix(bev), bev.size_px, flags=cv2.INTER_LINEAR
        )

    # -- persistence -------------------------------------------------------- #

    def to_dict(self) -> dict[str, Any]:
        d: dict[str, Any] = {
            "image_size": [int(self.image_size[0]), int(self.image_size[1])],
            "undistort_applied": bool(self.undistort_applied),
            "residual_m": float(self.residual_m),
            "H_image_to_ground": self.H_image_to_ground.tolist(),
        }
        if self.source_points_px is not None:
            d["image_points_px"] = np.asarray(self.source_points_px).tolist()
        if self.source_points_m is not None:
            d["world_points_m"] = np.asarray(self.source_points_m).tolist()
        return d

    @classmethod
    def from_dict(cls, d: dict[str, Any]) -> CameraModel:
        pts_px = d.get("image_points_px")
        pts_m = d.get("world_points_m")
        return cls(
            H_image_to_ground=np.asarray(d["H_image_to_ground"], dtype=np.float64),
            image_size=(int(d["image_size"][0]), int(d["image_size"][1])),
            undistort_applied=bool(d["undistort_applied"]),
            residual_m=float(d["residual_m"]),
            source_points_px=None if pts_px is None else np.asarray(pts_px, dtype=np.float64),
            source_points_m=None if pts_m is None else np.asarray(pts_m, dtype=np.float64),
        )

    def save(self, path: str | Path) -> Path:
        p = Path(path)
        p.parent.mkdir(parents=True, exist_ok=True)
        payload = {
            "_comment": (
                "Ground-plane homography mapping image pixels to ego metres "
                "(X right, Y forward, origin at the camera's ground projection). "
                "Generated by src/calibrate.py. All metric output in this project "
                "derives from this matrix."
            ),
            "created_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            **self.to_dict(),
        }
        p.write_text(yaml.safe_dump(payload, sort_keys=False), encoding="utf-8")
        return p

    @classmethod
    def load(cls, path: str | Path) -> CameraModel:
        p = Path(path)
        if not p.is_file():
            raise FileNotFoundError(
                f"homography not found: {p}. Run `python run.py calibrate homography` "
                f"first; distances cannot be computed without it and there is no "
                f"sensible default."
            )
        return cls.from_dict(yaml.safe_load(p.read_text(encoding="utf-8")))


def rectangle_world_points(width_m: float, near_m: float, far_m: float) -> np.ndarray:
    """World points for the common case: a road rectangle straddling the camera axis.

    Returns points in the order near-left, near-right, far-left, far-right, in
    ego metres. Use with image points clicked in the same order -- typically the
    two lane lines at a near and a far row of the image.
    """
    if width_m <= 0:
        raise ValueError(f"width_m must be > 0, got {width_m}")
    if not 0 < near_m < far_m:
        raise ValueError(f"need 0 < near_m < far_m, got near={near_m} far={far_m}")
    half = width_m / 2.0
    return np.array(
        [[-half, near_m], [half, near_m], [-half, far_m], [half, far_m]],
        dtype=np.float64,
    )


def pick_points_interactively(image: np.ndarray, n: int = 4) -> np.ndarray:
    """Open a window and collect ``n`` clicked points. Local display only.

    Click in the order the matching world points are listed: near-left,
    near-right, far-left, far-right for :func:`rectangle_world_points`. Backspace
    undoes the last click; Enter accepts once ``n`` points are placed; Esc aborts.

    This cannot run headless -- on Colab or CI, put the pixel coordinates in the
    config and use the non-interactive path instead.
    """
    picked: list[tuple[float, float]] = []
    window = "pick road points (click, backspace=undo, enter=accept, esc=abort)"

    def on_mouse(event: int, x: int, y: int, _flags: int, _param: Any) -> None:
        if event == cv2.EVENT_LBUTTONDOWN and len(picked) < n:
            picked.append((float(x), float(y)))

    try:
        cv2.namedWindow(window, cv2.WINDOW_NORMAL)
    except cv2.error as exc:  # pragma: no cover - depends on a display being present
        raise RuntimeError(
            "no display available for interactive point picking. Put the four "
            "pixel coordinates in the config and use the non-interactive path."
        ) from exc
    cv2.setMouseCallback(window, on_mouse)
    labels = ["near-left", "near-right", "far-left", "far-right"]
    try:
        while True:
            vis = image.copy()
            for i, (px, py) in enumerate(picked):
                cv2.circle(vis, (int(px), int(py)), 6, (0, 0, 255), -1)
                cv2.putText(
                    vis,
                    labels[i] if i < len(labels) else str(i),
                    (int(px) + 8, int(py) - 8),
                    cv2.FONT_HERSHEY_SIMPLEX,
                    0.6,
                    (0, 255, 255),
                    2,
                )
            if len(picked) > 1:
                cv2.polylines(
                    vis, [np.int32(picked)], len(picked) == n, (0, 255, 0), 2
                )
            nxt = labels[len(picked)] if len(picked) < len(labels) else "extra"
            cv2.putText(
                vis,
                f"{len(picked)}/{n} -- next: {nxt}",
                (12, 28),
                cv2.FONT_HERSHEY_SIMPLEX,
                0.8,
                (255, 255, 255),
                2,
            )
            cv2.imshow(window, vis)
            key = cv2.waitKey(20) & 0xFF
            if key == 27:
                raise KeyboardInterrupt("point picking aborted")
            if key == 8 and picked:
                picked.pop()
            if key in (13, 10) and len(picked) == n:
                break
    finally:
        cv2.destroyWindow(window)
    return np.array(picked, dtype=np.float64)


