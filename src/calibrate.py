"""Camera calibration: intrinsics from a chessboard, and a ground-plane homography.

Coordinate frames used throughout:
  * **image px** -- ``(u, v)``, origin at the top-left pixel, +u right, +v down.
    Always expressed in the *calibration* image size; see
    :meth:`CameraModel.for_image_size` for reading frames of another size.
  * **ego metres** -- ``(x, y)``, X right, Y forward, origin at the camera's
    ground projection. The road is assumed planar at Z = 0.
  * **BEV px** -- pixels of the rendered bird's-eye image, a pure affine
    rescaling of ego metres fixed by :class:`~src.config.BEVConfig`.

All metric output in this project comes from the homography here. There is no
depth network anywhere in the pipeline, so the quality of these four points sets
a hard ceiling on every distance, velocity and time-to-collision downstream.

Failures are loud: missing calibration files raise rather than falling back to
defaults, and points on or above the horizon raise rather than returning a
plausible-looking number.
"""

from __future__ import annotations

import argparse
import logging
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import cv2
import numpy as np
import yaml

from src.config import BEVConfig, ChessboardConfig, Config, load_config
from src.logging_utils import StageTimer, get_logger, log_kv

_log = get_logger(__name__)

#: Points whose projective denominator falls below this are treated as being on
#: the horizon, where the ground plane maps to infinity.
_HORIZON_EPS = 1e-9


# --------------------------------------------------------------------------- #
# Intrinsics
# --------------------------------------------------------------------------- #


@dataclass(frozen=True)
class Intrinsics:
    """Pinhole intrinsics and lens distortion for one camera.

    Attributes:
        camera_matrix: ``(3, 3)`` K, in pixels, for ``image_size``.
        dist_coeffs: OpenCV distortion vector, ``(5,)`` for the default model.
        image_size: ``(width, height)`` the calibration was performed at.
        rms_reprojection_error_px: OpenCV's overall RMS residual. Below ~0.5 px
            is good; above ~1.0 px means the board detections or the board
            geometry are suspect.
        n_images_used: Boards actually solved.
        n_images_total: Images offered.
    """

    camera_matrix: np.ndarray
    dist_coeffs: np.ndarray
    image_size: tuple[int, int]
    rms_reprojection_error_px: float
    n_images_used: int
    n_images_total: int

    def to_dict(self) -> dict[str, Any]:
        return {
            "image_size": [int(self.image_size[0]), int(self.image_size[1])],
            "rms_reprojection_error_px": float(self.rms_reprojection_error_px),
            "n_images_used": int(self.n_images_used),
            "n_images_total": int(self.n_images_total),
            "camera_matrix": self.camera_matrix.tolist(),
            "dist_coeffs": self.dist_coeffs.ravel().tolist(),
        }

    @classmethod
    def from_dict(cls, d: dict[str, Any]) -> Intrinsics:
        return cls(
            camera_matrix=np.asarray(d["camera_matrix"], dtype=np.float64).reshape(3, 3),
            dist_coeffs=np.asarray(d["dist_coeffs"], dtype=np.float64).reshape(1, -1),
            image_size=(int(d["image_size"][0]), int(d["image_size"][1])),
            rms_reprojection_error_px=float(d["rms_reprojection_error_px"]),
            n_images_used=int(d["n_images_used"]),
            n_images_total=int(d["n_images_total"]),
        )

    def save(self, path: str | Path) -> Path:
        p = Path(path)
        p.parent.mkdir(parents=True, exist_ok=True)
        payload = {
            "_comment": "Camera intrinsics from a chessboard. Generated by src/calibrate.py.",
            "created_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            **self.to_dict(),
        }
        p.write_text(yaml.safe_dump(payload, sort_keys=False), encoding="utf-8")
        return p

    @classmethod
    def load(cls, path: str | Path) -> Intrinsics:
        p = Path(path)
        if not p.is_file():
            raise FileNotFoundError(
                f"intrinsics not found: {p}. Run `python run.py calibrate intrinsics "
                f"--images <folder>` first; there is no default camera."
            )
        return cls.from_dict(yaml.safe_load(p.read_text(encoding="utf-8")))

    def undistort(self, image: np.ndarray) -> np.ndarray:
        """Return ``image`` with lens distortion removed, keeping the same size."""
        h, w = image.shape[:2]
        if (w, h) != self.image_size:
            raise ValueError(
                f"cannot undistort a {(w, h)} image with intrinsics calibrated at "
                f"{self.image_size}"
            )
        return cv2.undistort(image, self.camera_matrix, self.dist_coeffs)


def calibrate_intrinsics(
    image_dir: str | Path,
    board: ChessboardConfig,
    extensions: tuple[str, ...] = (".jpg", ".jpeg", ".png"),
    debug_dir: str | Path | None = None,
) -> Intrinsics:
    """Estimate intrinsics from a folder of chessboard photographs.

    Corners are refined to sub-pixel accuracy before solving. Images where the
    board is not fully visible are skipped and counted, not silently dropped.

    Intrinsics are in pixels, so a single calibration is only meaningful at a
    single resolution. If the folder mixes resolutions -- which real datasets do,
    sometimes by a single pixel -- the majority resolution is calibrated and the
    rest are excluded and reported, rather than being silently blended into one
    solve or aborting the whole run over an outlier.

    Args:
        image_dir: Folder of chessboard images.
        board: Inner-corner counts and physical square size.
        extensions: Image suffixes to consider.
        debug_dir: If set, write per-image corner visualisations here.

    Returns:
        The solved :class:`Intrinsics`.

    Raises:
        FileNotFoundError: if the folder holds no candidate images.
        ValueError: if too few boards were detected at the majority resolution.
    """
    d = Path(image_dir)
    if not d.is_dir():
        raise FileNotFoundError(f"chessboard image directory not found: {d}")
    files = sorted(p for p in d.iterdir() if p.suffix.lower() in extensions)
    if not files:
        raise FileNotFoundError(f"no images with extensions {list(extensions)} in {d}")

    # Board corners in board coordinates: Z = 0, spacing = one square.
    objp = np.zeros((board.rows * board.cols, 3), dtype=np.float32)
    objp[:, :2] = np.mgrid[0 : board.cols, 0 : board.rows].T.reshape(-1, 2)
    objp *= board.square_size_m

    criteria = (cv2.TERM_CRITERIA_EPS + cv2.TERM_CRITERIA_MAX_ITER, 30, 1e-3)
    #: size -> list of (filename, refined corners) for boards found at that size
    by_size: dict[tuple[int, int], list[tuple[str, np.ndarray]]] = {}
    no_board: list[str] = []

    if debug_dir is not None:
        Path(debug_dir).mkdir(parents=True, exist_ok=True)

    with StageTimer("calibrate.intrinsics", _log) as timer:
        for file in files:
            image = cv2.imread(str(file), cv2.IMREAD_COLOR)
            if image is None:
                raise OSError(f"could not decode calibration image: {file}")
            h, w = image.shape[:2]
            gray = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)
            found, corners = cv2.findChessboardCorners(
                gray,
                (board.cols, board.rows),
                flags=cv2.CALIB_CB_ADAPTIVE_THRESH + cv2.CALIB_CB_NORMALIZE_IMAGE,
            )
            timer.tick()
            if not found:
                no_board.append(file.name)
                continue
            corners = cv2.cornerSubPix(gray, corners, (11, 11), (-1, -1), criteria)
            by_size.setdefault((w, h), []).append((file.name, corners))
            if debug_dir is not None:
                vis = image.copy()
                cv2.drawChessboardCorners(vis, (board.cols, board.rows), corners, found)
                cv2.imwrite(str(Path(debug_dir) / f"corners_{file.stem}.jpg"), vis)

    if not by_size:
        raise ValueError(
            f"no image in {d} yielded a complete {board.cols}x{board.rows} board "
            f"({len(files)} tried). Check the inner-corner counts in configs "
            f"(cols/rows count INNER corners, not squares)."
        )

    # Intrinsics are pixel quantities, so calibrate at one resolution only.
    image_size = max(by_size, key=lambda k: len(by_size[k]))
    kept = by_size[image_size]
    wrong_size = [
        (name, size) for size, items in by_size.items() if size != image_size
        for name, _ in items
    ]
    if wrong_size:
        log_kv(
            _log,
            logging.WARNING,
            "calibrate.intrinsics.excluded_other_resolutions",
            calibrating_at=f"{image_size[0]}x{image_size[1]}",
            excluded=len(wrong_size),
            files=",".join(name for name, _ in wrong_size),
            note="intrinsics are in pixels; a single solve is valid at one resolution",
        )
    if len(kept) < 3:
        raise ValueError(
            f"only {len(kept)} of {len(files)} images yielded a complete "
            f"{board.cols}x{board.rows} board at {image_size[0]}x{image_size[1]}; "
            f"need at least 3."
        )

    object_points = [objp] * len(kept)
    image_points = [corners for _name, corners in kept]
    skipped = no_board + [name for name, _ in wrong_size]

    rms, K, dist, _rvecs, _tvecs = cv2.calibrateCamera(
        object_points, image_points, image_size, None, None
    )
    log_kv(
        _log,
        logging.INFO,
        "calibrate.intrinsics.done",
        images_used=len(object_points),
        images_total=len(files),
        skipped=len(skipped),
        rms_px=f"{rms:.4f}",
        fx=f"{K[0, 0]:.2f}",
        fy=f"{K[1, 1]:.2f}",
        cx=f"{K[0, 2]:.2f}",
        cy=f"{K[1, 2]:.2f}",
    )
    if skipped:
        log_kv(
            _log,
            logging.WARNING,
            "calibrate.intrinsics.skipped_images",
            files=",".join(skipped),
        )
    if rms > 1.0:
        log_kv(
            _log,
            logging.WARNING,
            "calibrate.intrinsics.high_residual",
            rms_px=f"{rms:.4f}",
            hint="above 1.0 px suggests bad corner detections or a wrong board spec",
        )
    return Intrinsics(
        camera_matrix=np.asarray(K, dtype=np.float64),
        dist_coeffs=np.asarray(dist, dtype=np.float64),
        image_size=image_size,
        rms_reprojection_error_px=float(rms),
        n_images_used=len(object_points),
        n_images_total=len(files),
    )


